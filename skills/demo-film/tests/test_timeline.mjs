// timeline.ts: the one clock. Pure; no render, no network.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';
import { AudioManifest, FilmScript, Take, holdMs } from '../tools/src/contract.ts';
import { DUCK_DB, LEAD_FRAMES, buildTimeline, dbToGain, duckAmount, musicGain, transitionProgress } from '../tools/remotion/timeline.ts';

const fx = path.join(path.dirname(fileURLToPath(import.meta.url)), 'fixtures', 'render');
const script = FilmScript.parse(JSON.parse(readFileSync(path.join(fx, 'film.json'), 'utf8')));
const clip = (id, ms) => ({ file: `audio/${id}.mp3`, ms, hash: 'x' });
const manifest = AudioManifest.parse({
  clips: { open: clip('open', 3030), 'haggle-open': clip('haggle-open', 4336), 'haggle-close': clip('haggle-close', 3944), end: clip('end', 2847) },
  music: { bed: { file: 'audio/music-bed.mp3', ms: 19043, hash: 'x' } },
});
// the take record is inlined (the fixture's take.json is generated by make-media.mjs)
const take = Take.parse({
  video: 'take/take.mp4', width: 1920, height: 1080, fps: 30, offsetUncertaintyMs: 0,
  beats: [
    { id: 'haggle-open', startMs: 500, endMs: 4900, rects: { '#offer': { x: 1180, y: 420, w: 420, h: 120 }, '#ceiling': { x: 1180, y: 600, w: 420, h: 120 } } },
    { id: 'haggle-close', startMs: 5200, endMs: 8600, rects: { '#offer': { x: 1180, y: 420, w: 420, h: 120 }, '#ceiling': { x: 1180, y: 600, w: 420, h: 120 } }, record: { ceiling: 340 } },
  ],
});
const tl = (balance = 'led') => buildTimeline({ script, manifest, take, balance });

test('beats tile the clock with holds from the contract, no gaps, no drift', () => {
  const t = tl();
  let ms = 0;
  t.beats.forEach((b, i) => {
    assert.equal(b.holdMs, holdMs(script.beats[i], script.breathMs, manifest.clips[b.id].ms));
    assert.equal(b.startFrame, Math.round((ms * 30) / 1000));
    if (i) assert.equal(b.startFrame, t.beats[i - 1].endFrame);
    ms += b.holdMs;
  });
  assert.equal(t.totalMs, ms);
  assert.equal(t.totalFrames, Math.round((ms * 30) / 1000));
});

test('estimated beats (no clip) time from the line and get no voice', () => {
  const t = buildTimeline({ script, manifest: AudioManifest.parse({ clips: {}, estimated: script.beats.map((b) => b.id) }), take, balance: 'led' });
  assert.ok(t.beats.every((b) => b.estimated));
  assert.equal(t.voice.length, 0);
  assert.equal(t.beats[0].holdMs, holdMs(script.beats[0], 350));
});

test('footage window = take beat; a shorter take holds the last frame instead of skipping', () => {
  const t = tl();
  const b = t.beats.find((x) => x.id === 'haggle-close');
  assert.equal(b.footage.trimBefore, Math.round((5200 * 30) / 1000));
  assert.equal(b.footage.availFrames, Math.round((3400 * 30) / 1000));
  assert.ok(b.footage.availFrames < b.durFrames);
  assert.ok(t.notes.some((n) => n.includes('haggle-close') && n.includes('last frame held')));
  assert.equal(t.beats[0].footage, undefined, 'pure motion beat has no footage');
});

test('balance filters moments by tier', () => {
  const ids = (b) => tl(b).moments.map((m) => m.id);
  assert.ok(!ids('overlay').includes('frame') && !ids('overlay').includes('claim'));
  assert.ok(ids('sandwich').includes('frame') && !ids('sandwich').includes('claim'));
  assert.ok(ids('led').includes('claim') && ids('led').includes('held'));
});

test('moments resolve to absolute frames: start, number, end', () => {
  const t = tl();
  const beat = (id) => t.beats.find((b) => b.id === id);
  const m = (id) => t.moments.find((x) => x.id === id);
  assert.equal(m('claim').startFrame, beat('haggle-open').startFrame);
  assert.equal(m('claim').durFrames, 45);
  assert.equal(m('l3').startFrame, beat('haggle-open').startFrame + 48);
  assert.equal(m('held').startFrame + m('held').durFrames, beat('haggle-close').endFrame);
  assert.ok(m('held').endsAtBeatEnd);
});

test('transitions split at the cut: out over the last half of one beat, in over the first half of the next', () => {
  const t = tl('led');
  const prev = t.beats.find((b) => b.id === 'haggle-open');
  const next = t.beats.find((b) => b.id === 'haggle-close');
  assert.equal(next.transitionIn.component, 'WhipPan');
  assert.equal(prev.transitionOut, next.transitionIn);
  const half = next.transitionIn.half;
  assert.equal(half, 6);
  assert.equal(transitionProgress(prev, prev.endFrame - 1).out.p, 1);
  assert.equal(transitionProgress(prev, prev.endFrame - half - 1).out, undefined);
  assert.ok(transitionProgress(next, next.startFrame).in.p > 0.8);
  assert.equal(transitionProgress(next, next.startFrame + half).in, undefined);
  assert.equal(t.totalFrames, tl('overlay').totalFrames, 'transitions never change the length');
  assert.equal(tl('overlay').beats.find((b) => b.id === 'haggle-close').transitionIn, undefined, 'tier-2 whip is a hard cut at overlay');
});

test('voice at beat start; chapter turns lead, clamped so voice never overlaps voice', () => {
  const t = tl();
  const v = (id) => t.voice.find((x) => x.beatId === id);
  assert.equal(v('open').from, 0);
  assert.equal(v('haggle-close').leadFrames, 0, 'same chapter: no lead');
  const turn = v('haggle-open');
  assert.ok(turn.leadFrames > 0 && turn.leadFrames <= LEAD_FRAMES);
  assert.ok(turn.from >= v('open').from + v('open').durFrames);
  // with room (long settle on the previous beat) the full 15-frame lead is used
  const roomy = FilmScript.parse({ ...script, beats: script.beats.map((b, i) => (i === 0 ? { ...b, settleMs: 5000 } : b)) });
  const t2 = buildTimeline({ script: roomy, manifest, take, balance: 'led' });
  assert.equal(t2.voice.find((x) => x.beatId === 'haggle-open').leadFrames, LEAD_FRAMES);
});

test('music: cue from structural edges, -18 dB bed, ducked 9 dB under voice with ramps, fades', () => {
  const t = tl();
  const c = t.music[0];
  assert.equal(c.from, 0);
  assert.equal(c.durFrames, t.totalFrames);
  assert.equal(c.gainDb, -18);
  const inVoice = t.voice[0].from + 20;
  assert.equal(duckAmount(t.voiceSpans, inVoice), 1);
  assert.ok(Math.abs(musicGain(c, t.voiceSpans, inVoice) - dbToGain(-18 - DUCK_DB)) < 1e-9);
  const free = t.voiceSpans[0][1] + 6;
  if (free + 6 < (t.voiceSpans[1]?.[0] ?? Infinity)) assert.ok(Math.abs(musicGain(c, t.voiceSpans, free) - dbToGain(-18)) < 1e-9, 'released between lines');
  const d = duckAmount(t.voiceSpans, t.voiceSpans[0][1] + 2);
  assert.ok(d > 0 && d < 1, '150 ms release ramp');
  assert.equal(musicGain(c, t.voiceSpans, 0), 0, 'fade in starts from silence');
  assert.ok(musicGain(c, t.voiceSpans, t.totalFrames - 1) < 0.05 * dbToGain(-18), 'fades out at the end');
});

test('fx: one whoosh per motion transition, peak on the cut', () => {
  const t = tl('led');
  assert.deepEqual(t.fx.map((f) => f.component), ['ZoomThrough', 'WhipPan', 'MaskWipe']);
  for (const f of t.fx) assert.equal(t.beats.find((b) => b.id === f.beatId).startFrame - f.from, Math.round(0.35 * 30));
  assert.deepEqual(tl('overlay').fx.map((f) => f.component), ['MaskWipe']);
});
