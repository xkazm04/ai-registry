#!/usr/bin/env node
// Marketplace builder — regenerates `.claude-plugin/marketplace.json` from the skills lane.
//
// The reference harness (Claude Code) distributes skills through PLUGIN MARKETPLACES: a
// consumer registers a marketplace once, enables the plugins it wants (per project, in
// `.claude/settings.json`, reviewed like code), and pulls new versions with one explicit
// command. That is exactly the sync model this lane wanted and could not enforce from a
// copy — version-pinned, per-project adoption, human act to update — so the registry IS a
// marketplace, and every skill in the lane is one single-skill plugin:
//
//   { name: "<skill>", source: "./skills/<skill>", version: "<frontmatter version>" }
//
// A plugin whose root holds SKILL.md (and no skills/ directory) loads as one skill named by
// its frontmatter `name`, invoked as `/<plugin>:<skill>` and — when nothing else claims the
// bare name — as `/<skill>`. One plugin per skill keeps adoption per skill and keeps the
// lane's fixed depth (`skills/<name>/SKILL.md`) untouched, because a plugin root is simply
// the skill directory the consumer's indexer already matches.
//
// GENERATED and gated: this file is a VIEW over the lane (the frontmatter is the authority),
// `--check` fails CI when the committed file is stale, and `claude plugin validate .` is
// the harness-side check to run locally. `version` is copied from the frontmatter because
// it is the update signal — a consumer receives a new copy exactly when the version moves,
// which is the same rule `check-skills.mjs --since` enforces on every pull request.
//
// NOT in this file: the registry's own maintenance skills (`.claude/skills/`) — they are
// slash commands for working ON the registry and are not library items.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readLane, parseSemver } from './lib/skills-lane.mjs';
import { sameIgnoringNewlines } from './lib/bundle-hash.mjs';

const ROOT = path.resolve(fileURLToPath(new URL('.', import.meta.url)), '..');
const LANE = path.join(ROOT, 'skills');
const OUT_DIR = path.join(ROOT, '.claude-plugin');
const OUT = path.join(OUT_DIR, 'marketplace.json');
const checkOnly = process.argv.includes('--check');

if (!fs.existsSync(LANE)) {
  console.error(`FATAL: no skills/ lane at ${LANE} — refusing to write a marketplace that lists zero plugins.`);
  process.exit(2);
}

const skills = readLane(LANE).filter((s) => s.exists && s.fm && s.fm.name);
if (skills.length === 0) {
  console.error('FATAL: the lane parsed to zero skills. THE READER IS BROKEN — not writing.');
  process.exit(2);
}

const plugins = [];
const skipped = [];
for (const s of skills) {
  if (!parseSemver(s.fm.version)) { skipped.push(`${s.name}: version ${JSON.stringify(s.fm.version)} is not semver (check-skills will fail it)`); continue; }
  if (s.fm.name !== s.name) { skipped.push(`${s.name}: frontmatter name ${JSON.stringify(s.fm.name)} != directory`); continue; }
  const entry = {
    name: s.name,
    source: `./skills/${s.name}`,
    description: String(s.fm.description ?? '').slice(0, 400),
    version: s.fm.version,
    category: s.fm.category ?? 'other',
  };
  const tags = Array.isArray(s.fm.tags) ? s.fm.tags : typeof s.fm.tags === 'string' ? s.fm.tags.split(',').map((t) => t.trim()).filter(Boolean) : [];
  if (tags.length) entry.tags = tags.slice(0, 12);
  plugins.push(entry);
}

const doc = {
  $schema: 'https://anthropic.com/claude-code/marketplace.schema.json',
  name: 'ai-registry',
  owner: { name: 'xkazm04', url: 'https://github.com/xkazm04/ai-registry' },
  metadata: {
    description: 'The ai-registry skills lane, one single-skill plugin per skill. GENERATED by scripts/build-marketplace.mjs from skills/<name>/SKILL.md frontmatter — edit the skill, bump its version, rebuild. Add with: claude plugin marketplace add xkazm04/ai-registry',
    version: '1',
  },
  plugins,
};
const serialized = `${JSON.stringify(doc, null, 2)}\n`;

if (checkOnly) {
  if (!fs.existsSync(OUT)) {
    console.error(`${path.relative(ROOT, OUT)} is MISSING — run \`node scripts/build-marketplace.mjs\` and commit the result.`);
    process.exit(1);
  }
  const current = fs.readFileSync(OUT, 'utf8');
  if (!sameIgnoringNewlines(current, serialized)) {
    console.error(`${path.relative(ROOT, OUT)} is STALE — run \`node scripts/build-marketplace.mjs\` and commit the result.`);
    try {
      const cur = JSON.parse(current).plugins ?? [];
      const curMap = new Map(cur.map((p) => [p.name, p.version]));
      for (const p of plugins) if (curMap.get(p.name) !== p.version) console.error(`  ${p.name}: committed ${curMap.get(p.name) ?? '(absent)'} -> computed ${p.version}`);
      for (const p of cur) if (!plugins.find((q) => q.name === p.name)) console.error(`  ${p.name}: committed but no longer in the lane`);
    } catch { /* unparseable committed file: the STALE verdict already says enough */ }
    process.exit(1);
  }
  console.log(`marketplace.json is fresh — ${plugins.length} plugin(s)${skipped.length ? `, ${skipped.length} skipped` : ''}`);
} else {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(OUT, serialized);
  console.log(`marketplace.json updated — ${plugins.length} plugin(s):`);
  for (const p of plugins) console.log(`  ${p.name}@${p.version} (${p.category})`);
}
for (const s of skipped) console.log(`  skipped: ${s}`);
