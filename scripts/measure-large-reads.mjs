#!/usr/bin/env node
// measure-large-reads.mjs — how much of a coding agent's context is spent on
// whole-file reads of large files, read from the harness's own session
// transcripts, and WHAT those files were.
//
// Zero dependencies. Reads ~/.claude/projects/**/*.jsonl (Claude Code session
// transcripts), finds every `Read` tool call with no offset/limit, measures the
// file as it exists NOW, and buckets each large read by the class of thing that
// produced the file:
//
//   harness-overflow   a tool-results/*.txt the harness spilled because a tool
//                      output was too large to show — reading it whole undoes
//                      the spill
//   generated-artifact a file whose first lines declare a generator or a ledger
//                      (a context snapshot, a run ledger)
//   source             everything else: code, docs, config the session works on
//
// Why the class matters: a size-only rule (block reads over N lines) fires
// hardest on exactly the source files a session needs whole, while the reads
// worth redirecting are the generated ones. The corpus states that rule
// (prompt-assembly/elision-to-a-refetch-pointer); this instrument is how a fleet
// checks it against its own transcripts before installing a hook.
//
// Every count carries its predicate (count-carries-predicate): the threshold,
// the cap the Read tool already applies, the estimator, and the fact that file
// sizes are measured today, not at read time.
//
//   node scripts/measure-large-reads.mjs                 # fleet-wide summary
//   node scripts/measure-large-reads.mjs --project kp    # one project dir match
//   node scripts/measure-large-reads.mjs --min 350 --cap 2000 --top 20 --json
//
// Exit 2 = instrument failure (no transcript root); exit 0 otherwise.

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';

const args = process.argv.slice(2);
const opt = (name, def) => { const i = args.indexOf(name); return i >= 0 && args[i + 1] ? args[i + 1] : def; };
const MIN = Number(opt('--min', 350));      // lines above which a whole read is "large"
const CAP = Number(opt('--cap', 2000));     // the Read tool's own default line cap — bytes past it never entered context
const TOP = Number(opt('--top', 15));
const PROJECT = opt('--project', null);
const JSON_OUT = args.includes('--json');
const ROOT = opt('--root', path.join(os.homedir(), '.claude', 'projects'));

if (!fs.existsSync(ROOT)) {
  console.error(`measure-large-reads: transcript root not found: ${ROOT}`);
  process.exit(2);
}

const BINARY = /\.(png|jpe?g|gif|webp|pdf|ico|svg|mp4|wav|mp3|zip|gz)$/i;
const GENERATED = /^\s*(?:>\s*)?(?:#.*)?(?:auto-?generated|generated:|generated by|\bledger\b)/i;

function classify(fp, firstLines) {
  if (/[\\/]tool-results[\\/]/.test(fp)) return 'harness-overflow';
  if (firstLines.some((l) => GENERATED.test(l))) return 'generated-artifact';
  return 'source';
}

const totals = { sessions: 0, readCalls: 0, targeted: 0, whole: 0, wholeMissingNow: 0, wholeBinary: 0, large: 0, largeEditedWithin4: 0 };
const byClass = {};
const byProject = {};
const files = {};
let minT = Infinity, maxT = 0;

for (const proj of fs.readdirSync(ROOT)) {
  if (PROJECT && !proj.includes(PROJECT)) continue;
  const pd = path.join(ROOT, proj);
  if (!fs.statSync(pd).isDirectory()) continue;
  const key = (proj.match(/kiro-([a-z-]+?)(?:-|$)/) || [])[1] || 'other';
  for (const f of fs.readdirSync(pd)) {
    if (!f.endsWith('.jsonl')) continue;
    let text; try { text = fs.readFileSync(path.join(pd, f), 'utf8'); } catch { continue; }
    const st = fs.statSync(path.join(pd, f)); minT = Math.min(minT, st.mtimeMs); maxT = Math.max(maxT, st.mtimeMs);
    totals.sessions++; byProject[key] = byProject[key] || { sessions: 0, large: 0, tokens: 0 }; byProject[key].sessions++;
    const calls = [];
    for (const line of text.split('\n')) {
      if (!line.startsWith('{')) continue;
      let j; try { j = JSON.parse(line); } catch { continue; }
      if (j.type !== 'assistant' || !j.message?.content) continue;
      for (const c of j.message.content) if (c.type === 'tool_use') calls.push({ name: c.name, input: c.input || {} });
    }
    for (let i = 0; i < calls.length; i++) {
      const c = calls[i]; if (c.name !== 'Read') continue; totals.readCalls++;
      const inp = c.input; const fp = String(inp.file_path || '');
      if (inp.offset != null || inp.limit != null) { totals.targeted++; continue; }
      totals.whole++;
      if (BINARY.test(fp)) { totals.wholeBinary++; continue; }
      let body; try { body = fs.readFileSync(fp, 'utf8'); } catch { totals.wholeMissingNow++; continue; }
      const lines = body.split('\n'); if (lines.length <= MIN) continue;
      const cls = classify(fp, lines.slice(0, 8));
      const tokens = Math.round(lines.slice(0, CAP).join('\n').length / 4);
      totals.large++;
      byClass[cls] = byClass[cls] || { reads: 0, tokens: 0 }; byClass[cls].reads++; byClass[cls].tokens += tokens;
      byProject[key].large++; byProject[key].tokens += tokens;
      files[fp] = files[fp] || { lines: lines.length, cls, reads: 0, tokens }; files[fp].reads++;
      for (let k = i + 1; k < Math.min(i + 5, calls.length); k++) {
        const d = calls[k];
        if ((d.name === 'Edit' || d.name === 'Write' || d.name === 'MultiEdit') && d.input.file_path === fp) { totals.largeEditedWithin4++; break; }
      }
    }
  }
}

const predicate = {
  threshold_lines: MIN, read_tool_cap_lines: CAP, token_estimator: 'chars/4 over the first CAP lines',
  file_size_measured: 'today, not at read time (deleted files are counted as wholeMissingNow and excluded)',
  edited_within: '4 tool calls, same path',
  span: Number.isFinite(minT) ? `${new Date(minT).toISOString().slice(0, 10)} .. ${new Date(maxT).toISOString().slice(0, 10)}` : 'n/a',
};
const topFiles = Object.entries(files).sort((a, b) => b[1].reads * b[1].tokens - a[1].reads * a[1].tokens).slice(0, TOP)
  .map(([fp, v]) => ({ file: fp, lines: v.lines, class: v.cls, reads: v.reads }));

if (JSON_OUT) { console.log(JSON.stringify({ predicate, totals, byClass, byProject, topFiles }, null, 1)); process.exit(0); }

console.log(`measure-large-reads — ${predicate.span}  root=${ROOT}${PROJECT ? `  project~${PROJECT}` : ''}`);
console.log(`  predicate: whole Read (no offset/limit) of a text file > ${MIN} lines; tokens = chars/4 over first ${CAP} lines; sizes measured today`);
console.log(`  sessions ${totals.sessions} · Read calls ${totals.readCalls} · targeted ${totals.targeted} · whole ${totals.whole} (binary ${totals.wholeBinary}, missing now ${totals.wholeMissingNow})`);
console.log(`  LARGE whole reads: ${totals.large}   edited within 4 calls: ${totals.largeEditedWithin4}`);
console.log('\n  by class of what produced the file:');
for (const [k, v] of Object.entries(byClass).sort((a, b) => b[1].tokens - a[1].tokens)) console.log(`    ${k.padEnd(20)} reads ${String(v.reads).padStart(4)}   ~tokens ${String(v.tokens).padStart(9)}   per read ${Math.round(v.tokens / v.reads)}`);
console.log('\n  by project (rate = sessions per large read):');
for (const [k, v] of Object.entries(byProject).filter(([, v]) => v.large).sort((a, b) => b[1].large - a[1].large))
  console.log(`    ${k.padEnd(14)} sessions ${String(v.sessions).padStart(5)}   large ${String(v.large).padStart(4)}   1 in ${String(Math.round(v.sessions / v.large)).padStart(4)}   ~tokens ${v.tokens}`);
console.log(`\n  top ${TOP} files by reads x tokens:`);
for (const t of topFiles) console.log(`    ${String(t.lines).padStart(6)} lines  x${t.reads}  ${t.class.padEnd(18)} ${t.file}`);
console.log('\n  NOT measured: what the session did with the bytes, whether a targeted read would have sufficed, the delegate cost of any redirect.');
