// Seeded canaries for check-coverage-age (2026-10-25 gates scan): a future stamp, a decoy
// fresh stamp above the real one, and a report declaring 0 projects all read "Fresh". The
// gate reads its report from its own location, so each case copies it into a temp tree
// with a synthetic librarian/fleet-coverage.md stamped relative to now.
import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const SCRIPTS = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const made = [];
after(() => { for (const d of made) fs.rmSync(d, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 }); });

const daysAgo = (n) => new Date(Date.now() - n * 86_400_000).toISOString().replace(/\.\d{3}Z$/, 'Z');
const header = (stamp, projects = 18) =>
  `<!-- GENERATED by scripts/converge.mjs. Do not hand-edit. -->\n\ngenerated: ${stamp} · machine: Box · projects declared: ${projects}\n`;

function run(report) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'coverage-age-'));
  made.push(root);
  fs.mkdirSync(path.join(root, 'scripts', 'lib'), { recursive: true });
  for (const f of ['check-coverage-age.mjs', 'lib/exit-codes.mjs', 'lib/check-result.mjs']) {
    fs.copyFileSync(path.join(SCRIPTS, f), path.join(root, 'scripts', f));
  }
  if (report !== null) {
    fs.mkdirSync(path.join(root, 'librarian'));
    fs.writeFileSync(path.join(root, 'librarian', 'fleet-coverage.md'), `# Fleet coverage\n\n${report}\n## Totals\n`);
  }
  return spawnSync(process.execPath, [path.join(root, 'scripts', 'check-coverage-age.mjs')], { encoding: 'utf8' });
}

test('control: a fresh report with a declared population passes', () => {
  const r = run(header(daysAgo(2)));
  assert.equal(r.status, 0, r.stderr);
  assert.match(r.stdout, /Fresh/);
});

test('a stale report is a violation (1); a missing one too', () => {
  assert.equal(run(header(daysAgo(30))).status, 1);
  assert.equal(run(null).status, 1);
});

test('a future stamp (2099) is a violation, not a fresh measurement', () => {
  const r = run(header('2099-01-01T00:00:00Z'));
  assert.equal(r.status, 1);
  assert.match(r.stderr, /in the future/);
});

test('a decoy fresh stamp above the real stale one cannot establish the age (2)', () => {
  const r = run(`generated: ${daysAgo(0)}\n\n${header(daysAgo(40))}`);
  assert.equal(r.status, 2);
  assert.match(r.stderr, /2 `generated:` stamps/);
});

test('zero projects declared, or no population at all, is could-not-run (2)', () => {
  const zero = run(header(daysAgo(1), 0));
  assert.equal(zero.status, 2);
  assert.match(zero.stderr, /walked 0 projects declared/);
  assert.equal(run(`generated: ${daysAgo(1)}\n`).status, 2);
});

test('an unreadable stamp stays could-not-run (2)', () => {
  assert.equal(run('generated: not-a-date · projects declared: 3\n').status, 2);
});
